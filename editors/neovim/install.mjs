#!/usr/bin/env node
// Install utu support into Neovim (0.11+) as one package:
// ~/.local/share/nvim/site/pack/utu/start/utu/, holding the language server
// setup and filetype (plugin/utu.lua), the tree-sitter grammars (utu, and
// Wutu for `@wutu/\ … \/`) built from this repository, and their queries.
//
//   node editors/neovim/install.mjs            install or update
//   node editors/neovim/install.mjs --remove   take it out again
//
// The queries are Helix's (editors/helix/queries), renamed to Neovim's
// capture names here, so there is one set to keep.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const data = process.env.XDG_DATA_HOME ?? path.join(os.homedir(), '.local', 'share');
const pack = path.join(data, 'nvim', 'site', 'pack', 'utu', 'start', 'utu');
const helix = path.join(repo, 'editors', 'helix', 'queries');
const grammarSources = { utu: path.join(repo, 'editors', 'tree-sitter-utu'), wutu: path.join(repo, 'editors', 'tree-sitter-wutu') };

fs.rmSync(pack, { recursive: true, force: true });
if (process.argv.includes('--remove')) {
  console.log(`removed ${pack}`);
  process.exit(0);
}

// Helix's capture names where Neovim's differ (Neovim falls back from
// `@a.b.c` to `@a.b` and `@a`, so only names with no good fallback are here).
const HIGHLIGHTS = {
  'namespace': 'module',
  'variable.other.member': 'variable.member',
  'constant.numeric.integer': 'number',
  'constant.numeric.float': 'number.float',
  'constant.numeric': 'number',
  'constant.builtin.boolean': 'boolean',
  'type.enum.variant': 'constant',
  'keyword.special': 'keyword.modifier',
};
// Helix's one `@keyword.control` list, split into Neovim's kinds (a word in
// none stays `@keyword.control`, which falls back to `@keyword`).
const CONTROL = {
  conditional: ['if', 'else', 'match', 'alt', 'promote', 'orelse'],
  repeat: ['for', 'while', 'loop', 'continue', 'break'],
  return: ['return', 'yield'],
  exception: ['try', 'catch', 'defer', 'errdefer', 'assert', 'fatal'],
  coroutine: ['await'],
};
const splitControl = text => text.replace(/\[([^\]]*)\]\s*@keyword\.control\b/g, (all, list) => {
  const words = [...list.matchAll(/"([^"]+)"/g)].map(m => m[1]);
  const groups = Object.entries(CONTROL).map(([kind, of]) => [kind, words.filter(w => of.includes(w))]).filter(([, ws]) => ws.length);
  const rest = words.filter(w => !Object.values(CONTROL).flat().includes(w));
  if (rest.length) groups.push(['control', rest]);
  return groups.map(([kind, ws]) => `[ ${ws.map(w => `"${w}"`).join(' ')} ] @keyword.${kind}`).join('\n');
});
// nvim-treesitter's indent and text-object names.
const INDENTS = { 'indent': 'indent.begin', 'outdent': 'indent.branch' };
const rename = (text, names) => text.replace(/@([a-z][a-z.]*)/g, (all, name) => names[name] ? `@${names[name]}` : all);
const textobjects = text => text.replace(/@([a-z]+)\.(around|inside)\b/g, (_, what, part) => `@${what}.${part === 'around' ? 'outer' : 'inner'}`);

for (const language of ['utu', 'wutu']) {
  const out = path.join(pack, 'queries', language);
  fs.mkdirSync(out, { recursive: true });
  const read = name => {
    const file = path.join(helix, language, name);
    return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  };
  const header = `; Generated by editors/neovim/install.mjs from editors/helix/queries/${language}.\n`;
  const write = (name, text) => text !== null && fs.writeFileSync(path.join(out, name), header + text);
  write('highlights.scm', splitControl(rename(read('highlights.scm'), HIGHLIGHTS)));
  write('injections.scm', read('injections.scm'));
  write('indents.scm', rename(read('indents.scm'), INDENTS));
  write('textobjects.scm', read('textobjects.scm') && textobjects(read('textobjects.scm')));
  // Folds: what indents.
  const indents = read('indents.scm');
  const folds = indents?.match(/\[([\s\S]*?)\]\s*@indent\b/)?.[1];
  if (folds) write('folds.scm', `[${folds}] @fold\n`);
}
console.log(`wrote queries to ${path.join(pack, 'queries')}`);

fs.mkdirSync(path.join(pack, 'plugin'), { recursive: true });
fs.writeFileSync(path.join(pack, 'plugin', 'utu.lua'),
  fs.readFileSync(path.join(here, 'plugin', 'utu.lua'), 'utf8').replaceAll('@REPO@', repo));
console.log(`wrote ${path.join(pack, 'plugin', 'utu.lua')}`);

// The grammars, each built from its src/parser.c and src/scanner.c.
const parsers = path.join(pack, 'parser');
fs.mkdirSync(parsers, { recursive: true });
for (const [name, source] of Object.entries(grammarSources)) {
  const library = path.join(parsers, `${name}.so`);
  const cc = spawnSync(process.env.CC ?? 'cc', ['-shared', '-fPIC', '-O2', '-I', path.join(source, 'src'),
    path.join(source, 'src', 'parser.c'), path.join(source, 'src', 'scanner.c'), '-o', library], { encoding: 'utf8' });
  if (cc.error || cc.status !== 0) {
    console.error(`could not build the ${name} grammar: ${cc.error?.message ?? cc.stderr}`);
    process.exit(1);
  }
  console.log(`built the ${name} grammar: ${library}`);
}

// A check: Neovim parses a sample with the grammar and reads every query.
const check = spawnSync('nvim', ['--headless', '--clean', '--cmd', `set rtp^=${pack}`, '-c',
  `lua for _, l in ipairs({'utu', 'wutu'}) do for _, q in ipairs({'highlights', 'injections', 'folds', 'indents'}) do `
  + `local ok, err = pcall(vim.treesitter.query.get, l, q) if not ok then io.stderr:write(l .. '/' .. q .. ': ' .. err .. '\\n') vim.cmd('cq') end end end`,
  '-c', 'qa'], { encoding: 'utf8' });
if (check.error) console.log('(nvim not found: queries not checked)');
else if (check.status !== 0) { console.error(`Neovim rejected a query:\n${check.stderr}`); process.exit(1); }
else console.log('Neovim loads the grammars and every query');
